"""FCVTZS's fast path in recomp_fp_to_int (nx2/suyu_rt_fixes.py over suyu/arm64_to_c.h's FPFixedHelpers), game-free:
bit-exact with the exact body.

For a normal input below 2^(int_bits-1) in magnitude, FCVTZS (signed, toward zero) takes the C conversion and sets IXC
when the result differs from the input; everything else (zeros, subnormals and FZ, infinities, NaNs, saturation) runs
the exact body. This cuts the helpers out of the emitter's source, as the runtime header pastes them, applies
nx2/suyu_rt_fixes.py's fcvtzs() as the lift does, and builds
tests/fcvtzs_fast_test.c against two copies: as written, and with RECOMP_NO_NATIVE_FP (the exact body only). Value and
FPSR must match for 4M random cases (seeded: exponents around both edges of the fast path, any bits, specials, FZ and
other FPCR bits, sticky FPSR) and an edge sweep (every exponent, 10 mantissas, both signs, 4 FPCR and 3 FPSR states),
S and D to W and X, at -O2 -ffp-contract=off for -march=x86-64 and x86-64-v3 (the v3 build is skipped on a CPU without
it). `fcvtzs_fast_test all32` checks every binary32 input (about a minute; not run here).

It has teeth: the range check one exponent wider (`bias + int_bits - 2u` made `- 1u`) fails both runs with the
saturating inputs at 2^(int_bits-1); IXC dropped from the fast path fails both; without fcvtzs() it stops.

    python -I -B tests/test_fcvtzs_fast.py [--cc clang]

Skipped (exit 0) on a host with no C compiler (PATH, $CC, or the build's own toolchain).
"""
import argparse
import importlib.util
import os
import platform
import re
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "third_party", "a64-kit", "lift", "suyu", "arm64_to_c.h")
sys.path.insert(0, os.path.join(ROOT, "nx2"))
import suyu_rt_fixes  # noqa: E402

RANDOM_CASES, SEED = 4000000, 20261111
FLAGS = ["-ffp-contract=off", "-fno-strict-aliasing", "-O2", "-Wall", "-Werror"]


def helpers():
    """FPScanHelpers' and FPFixedHelpers' C, as the runtime header pastes them"""
    text = open(SOURCE, encoding="utf-8").read()
    parts = []
    for name, tag in (("FPScanHelpers", "FS"), ("FPFixedHelpers", "FX")):
        m = re.search(r'inline const char\* %s\(\) \{\n    return R"%s\((.*?)\)%s";' % (name, tag, tag), text, re.S)
        if not m:
            raise SystemExit("fcvtzs fast: %s not found in arm64_to_c.h: update this test" % name)
        parts.append(m.group(1))
    parts[1] = suyu_rt_fixes.fcvtzs(parts[1])
    a = parts[1].find("static RECOMP_INLINE uint64_t recomp_fp_to_int(")
    if a < 0 or "#ifndef RECOMP_NO_NATIVE_FP" not in parts[1][a:parts[1].find("\n}\n", a)]:
        raise SystemExit("fcvtzs fast: recomp_fp_to_int has no native path to check")
    return parts


def header(parts):
    scan, fixed = parts
    names = re.compile(r"\b(?:%s)\b" % "|".join(re.findall(r"^static RECOMP_INLINE \w+ (recomp_\w+)\(", fixed, re.M)))

    def renamed(prefix):
        return names.sub(lambda m: prefix + m.group(0)[len("recomp_"):], fixed)
    return "\n".join([
        "/* Generated by tests/test_fcvtzs_fast.py from suyu/arm64_to_c.h. */",
        "#include <stdint.h>",
        "#include <string.h>",
        scan,
        renamed("fast_"),
        "#define RECOMP_NO_NATIVE_FP",
        renamed("ref_"),
        "#undef RECOMP_NO_NATIVE_FP",
        ""])


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cc")
    a = p.parse_args()
    spec = importlib.util.spec_from_file_location("fpx_sticky", os.path.join(ROOT, "tests", "test_fpx_sticky.py"))
    sticky = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(sticky)
    cc = sticky.compiler(a.cc, "CC", ("clang", "gcc", "cc"), "clang")
    if not cc:
        print("fcvtzs fast: skipped (no C compiler)")
        return
    x86 = platform.machine().lower() in ("x86_64", "amd64")
    builds = (("x86-64", 0), ("x86-64-v3", 1)) if x86 else (("", 0),)
    t0 = time.time()
    failed, ran = [], 0
    with tempfile.TemporaryDirectory(prefix="hookshot-fcvtzs-fast-") as tmp:
        with open(os.path.join(tmp, "fcvtzs_fast.h"), "w", encoding="utf-8", newline="\n") as f:
            f.write(header(helpers()))
        for march, v3 in builds:
            exe = os.path.join(tmp, "fcvtzs_fast_test_%s.exe" % (march or "native"))
            sticky.build([cc] + sticky.target_flags(cc, tmp) + (["-march=" + march] if march else []) + FLAGS +
                         (["-DNEED_V3"] if v3 else []) + ["-I" + tmp, os.path.join(ROOT, "tests", "fcvtzs_fast_test.c"),
                                                          "-o", exe], "the driver " + march)
            for args in (["random", str(RANDOM_CASES), str(SEED)], ["edges"]):
                r = sticky.run([exe] + args)
                print(r.stdout.rstrip())
                if r.returncode == 3:
                    print("fcvtzs fast: %s skipped (this CPU is not %s)" % (march, march))
                    break
                ran += 1
                if r.returncode:
                    failed.append("%s %s" % (march, args[0]))
    if failed:
        raise SystemExit("fcvtzs fast: FAIL (%s) in %.1f s" % (", ".join(failed), time.time() - t0))
    print("fcvtzs fast: pass (%d runs) in %.1f s" % (ran, time.time() - t0))


if __name__ == "__main__":
    sys.exit(main())
